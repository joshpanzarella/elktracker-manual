// 12 x 24 px cell). '#' = on.
//
// READ FROM THE DEVICE (a photo of the Song screen, perspective-corrected and
// sampled pixel by pixel, several copies voted where they appear):
//   0-9  A-I  L-P  S T U Z  -  :
// Note the device's own shapes: a dotted slash in 0, an open-top 4, a 6
// whose middle bar leaves the left stroke, a 7 with a kink.
//
// DRAWN TO MATCH (not yet seen on the device, so check them against it):
//   J K Q R V W X Y, every lowercase letter, and the other symbols.
//
// A glyph can have an 8th row for descenders, and `dy` nudges it down by
// device pixels (the device's dash sits 1 px below the 5x7 grid).

export interface Glyph {
  rows: string[];
  dy?: number;
}

const g = (rows: string, dy?: number): Glyph => ({ rows: rows.trim().split(/\s+/), dy });

